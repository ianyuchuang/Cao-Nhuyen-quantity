# ---- 同型樓層轉換：依位置與代號對到範本層，房號換樓層前綴 ----
import numpy as np, sys
sys.path.insert(0,'.')
from common import *
cal=json.load(open('calib.json',encoding='utf-8')); TAGS=load_tags(); D=load_dwg()
DR=collections.defaultdict(set)
for n,p in D['room']: DR[band(p[1])].add(n)
OFF={f:(int(f[:-1])-1)*10000 for f in ['1F','2F','3F','4F','5F','7F','8F','9F','10F','11F']}; OFF['6F']=10000*5+715
def pos(t):
    A=np.array(cal[t['fl']]['A']); p=A@np.array([t['x'],t['y'],1]); return p[0],p[1]-OFF[t['fl']]
PENDING=[]
def transfer(ref,tgt,tol=150,skip=()):
    R=[(t,pos(t)) for t in TAGS if t['fl']==ref]
    pre=tgt[:-1]
    for t in TAGS:
        if t['fl']!=tgt or t['seq'].split('-',1)[1] in skip: continue
        p=pos(t)
        c=[(np.hypot(q[0]-p[0],q[1]-p[1]),r) for r,q in R if r['code']==t['code']]
        if not c: PENDING.append((t['seq'],'範本層無同代號')); continue
        dd,r=min(c,key=lambda x:x[0])
        if dd>tol: PENDING.append((t['seq'],f"最近同代號 {r['seq']} 相距 {dd:.0f}cm")); continue
        e=M.get(r['seq'])
        if not e: PENDING.append((t['seq'],f"範本 {r['seq']} 未核定")); continue
        src=e.get('verify',e.get('room'))
        if src is None:
            M[t['seq']]=dict(room=None,why=e['why']+f'（同 {r["seq"]}）',conf=''); continue
        new=pre+src[len(ref[:-1]):]
        if new not in DR[tgt]: PENDING.append((t['seq'],f'{new} 不在 DWG 房號')); continue
        why=e.get('why',f'同 {r["seq"]}（已目視核對）')
        M[t['seq']]=dict(room=new,why=why.replace(src,new) if 'why' in e else why,conf=e.get('conf','高'),tr=r['seq'])
transfer('8F','9F'); transfer('8F','10F')
print('待人工:',PENDING)
json.dump(M,open('manual.json','w',encoding='utf-8'),ensure_ascii=False,indent=0)
print(len(M))
