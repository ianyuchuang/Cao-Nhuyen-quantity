def seglen(s, sc):
    (x1, y1), (x2, y2) = s
    return math.hypot((x2 - x1) * sc[0], (y2 - y1) * sc[1]) / 100

def poly_segs(pts, skip=()):
    return [[list(pts[i]), list(pts[(i + 1) % len(pts)])] for i in range(len(pts)) if i not in skip]

def rect(x0, y0, x1, y1): return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]

def rect_alcove(x0, y0, x1, y1, ax0, ax1, ay1):
    return [(x0, y0), (x1, y0), (x1, y1), (ax1, y1), (ax1, ay1), (ax0, ay1), (ax0, y1), (x0, y1)]

